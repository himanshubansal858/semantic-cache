import { generateAnswer } from "../services/llmService.js";
import { generateEmbedding } from "../services/embeddingService.js";
import {
    findCacheMatch,
    storeCacheEntry
} from "../services/vectorStore.js";

export const askQuestion = async (req, res) => {
    try {
        const { question } = req.body || {};

        // 1. Validate the question
        if (typeof question !== "string" || !question.trim()) {
            return res.status(400).json({
                success: false,
                message: "A valid question is required"
            });
        }

        // 2. Generate embedding for the incoming question
        const embedding = await generateEmbedding(question);

        // 3. Search Redis for a similar cached question
        const cacheResult = await findCacheMatch(embedding);

        // 4. If cache hit, return the cached answer
        if (cacheResult.cacheHit) {
            return res.status(200).json({
                success: true,
                question,
                answer: cacheResult.answer,
                cache: {
                    hit: true,
                    similarity: cacheResult.similarity
                }
            });
        }

        // 5. If cache miss, generate a fresh answer using Gemini
        const answer = await generateAnswer(question);

        // 6. Store the new question, answer, and embedding in Redis
        await storeCacheEntry(question, answer, embedding);

        // 7. Return the newly generated answer
        return res.status(200).json({
            success: true,
            question,
            answer,
            cache: {
                hit: false,
                message: "Answer generated by Gemini and stored in cache"
            }
        });

    } catch (error) {
        console.error("Controller Error:", error);

        return res.status(500).json({
            success: false,
            message: error.message
        });
    }
};
